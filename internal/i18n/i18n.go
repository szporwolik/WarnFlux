// Package i18n provides the WarnFlux UI translations. The default
// language is English; Polish is the second supported language. The
// language is resolved from the wf_lang cookie, then the browser's
// Accept-Language header, then English.
package i18n

import (
	"net/http"
	"strings"
)

// Language codes.
const (
	LangEN = "en"
	LangPL = "pl"
)

// Default is the fallback language.
const Default = LangEN

// catalogs maps language code -> key -> translation. English is the
// fallback: a missing key in another language falls back to English.
var catalogs = map[string]map[string]string{
	LangEN: en,
	LangPL: pl,
}

// Supported reports whether code is a supported UI language.
func Supported(code string) bool {
	_, ok := catalogs[code]
	return ok
}

// T returns the translation of key in lang; unsupported languages and
// missing keys fall back to English, then to the key itself.
func T(lang, key string) string {
	if m, ok := catalogs[lang]; ok {
		if s, ok := m[key]; ok {
			return s
		}
	}
	if s, ok := en[key]; ok {
		return s
	}
	return key
}

// FromRequest resolves the UI language for a request: the wf_lang cookie
// wins, then the browser's Accept-Language list, then English.
func FromRequest(r *http.Request) string {
	if c, err := r.Cookie("wf_lang"); err == nil && Supported(c.Value) {
		return c.Value
	}
	if r.Header.Get("Accept-Language") != "" {
		for _, part := range strings.Split(r.Header.Get("Accept-Language"), ",") {
			code := strings.TrimSpace(strings.SplitN(part, ";", 2)[0])
			code = strings.ToLower(code)
			if code == LangPL || strings.HasPrefix(code, LangPL+"-") {
				return LangPL
			}
			if code == LangEN || strings.HasPrefix(code, LangEN+"-") || code == "*" {
				return LangEN
			}
		}
	}
	return Default
}

