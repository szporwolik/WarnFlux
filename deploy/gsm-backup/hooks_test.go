// TestDownIsIdempotentAndSafeOnAPlainFile covers the ordinary host (a regular
// resolv.conf) and a repeated ip-down: the second run must change nothing.
func TestDownIsIdempotentAndSafeOnAPlainFile(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()

	for i := 0; i < 2; i++ {
		s.run(hookEnv{
			script: "90-warnflux-gsm",
			args:   pppArgs("ppp0", "warnflux-gsm"),
			env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "10.0.0.53"},
		})
	}
	if n := strings.Count(read(t, conf), "nameserver 10.0.0.53"); n != 1 {
		t.Errorf("two ip-up runs produced %d fallback entries, want 1", n)
	}

	s.run(hookEnv{script: "90-warnflux-gsm-down", args: pppArgs("ppp0", "warnflux-gsm"),
		env: map[string]string{"WARNFLUX_RESOLVCONF": conf}})
	once := read(t, conf)
	s.run(hookEnv{script: "90-warnflux-gsm-down", args: pppArgs("ppp0", "warnflux-gsm"),
		env: map[string]string{"WARNFLUX_RESOLVCONF": conf}})
	if twice := read(t, conf); twice != once {
		t.Errorf("a repeated ip-down changed the file:\n%s\nwant:\n%s", twice, once)
	}
	if !strings.Contains(once, "nameserver 10.0.0.1") {
		t.Errorf("the wired resolver was lost:\n%s", once)
	}
}

// TestResolvedHostsUseResolvectl prefers the daemon: on a host running
// systemd-resolved, resolv.conf is a stub file it regenerates, so a hand-edited
// block would vanish — and the syadmin would never see why.
func TestResolvedHostsUseResolvectl(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	s.silentResolved()
	conf := s.writeConf()
	before := read(t, conf)

	s.run(hookEnv{
		script: "90-warnflux-gsm",
		args:   pppArgs("ppp0", "warnflux-gsm"),
		env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "10.0.0.53"},
	})
	s.run(hookEnv{script: "90-warnflux-gsm-down", args: pppArgs("ppp0", "warnflux-gsm"),
		env: map[string]string{"WARNFLUX_RESOLVCONF": conf}})

	calls := s.calls()
	if !strings.Contains(calls, "resolvectl dns ppp0 10.0.0.53") {
		t.Errorf("the per-link resolver was not set: %s", calls)
	}
	if !strings.Contains(calls, "resolvectl revert ppp0") {
		t.Errorf("the per-link resolver was not reverted: %s", calls)
	}
	if got := read(t, conf); got != before {
		t.Errorf("resolv.conf was edited even though resolved owns it:\n%s", got)
	}
}

// TestEnsureKeepsANewerDHCPResolver is WF-R3-01: pppd's pre-connect copy is
// history. Once NetworkManager has written a new resolver for the wired link
// (a new router, a new subnet, a new operator DNS), rebuilding the block must
// keep the new address — restoring the old one would leave the station asking
// a resolver that may no longer exist.
func TestEnsureKeepsANewerDHCPResolver(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()
	if err := os.WriteFile(conf+".pppd-backup.ppp0", []byte("nameserver 192.0.2.10\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(s.dir, "state"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(s.dir, "state", "ppp0.dns"),
		[]byte("nameserver 198.51.100.53\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	env := map[string]string{"WARNFLUX_RESOLVCONF": conf}

	// The operator's DNS is already in the block, and DHCP has since installed a
	// new wired resolver and dropped our block.
	if err := os.WriteFile(conf, []byte("# Generated by NetworkManager\nnameserver 192.0.2.20\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"ensure", "ppp0", "wired"}, env: env})

	body := read(t, conf)
	if !strings.Contains(body, "nameserver 192.0.2.20") {
		t.Errorf("the new DHCP resolver was replaced:\n%s", body)
	}
	if strings.Contains(body, "192.0.2.10") {
		t.Errorf("the pre-connect copy came back:\n%s", body)
	}
	if !strings.Contains(body, "nameserver 198.51.100.53") {
		t.Errorf("the operator fallback is missing:\n%s", body)
	}

	// Repeated passes and a failover round trip do not resurrect the old one.
	for _, order := range []string{"cellular", "wired", "cellular", "wired"} {
		s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"ensure", "ppp0", order}, env: env})
	}
	if body := read(t, conf); strings.Contains(body, "192.0.2.10") {
		t.Errorf("a failover round trip restored the stale resolver:\n%s", body)
	}
}

// TestEnsureIgnoresAnotherPPPsResolvers is WF-R3-02: /etc/ppp/resolv.conf is
// shared by every PPP profile on the host, so a VPN or a second modem that
// connects later overwrites it. The backup link must rebuild its fallback entry
// from its OWN record, never from that file.
func TestEnsureIgnoresAnotherPPPsResolvers(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()
	if err := os.MkdirAll(filepath.Join(s.dir, "state"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(s.dir, "state", "ppp0.dns"), []byte("nameserver 198.51.100.53\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	// The shared PPP file now belongs to somebody else.
	shared := filepath.Join(s.dir, "ppp-resolv.conf")
	if err := os.WriteFile(shared, []byte("nameserver 203.0.113.53\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	env := map[string]string{"WARNFLUX_RESOLVCONF": conf}

	s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"ensure", "ppp0", "cellular"}, env: env})
	body := read(t, conf)
	if strings.Contains(body, "203.0.113.53") {
		t.Errorf("another profile's resolver reached the backup link:\n%s", body)
	}
	if !strings.Contains(body, "nameserver 198.51.100.53") {
		t.Errorf("our own resolver is missing:\n%s", body)
	}
}

// TestHooksKeepTheirOwnSessionState covers the record the watchdog rebuilds
// from: ip-up writes it for its interface, ip-down removes only that one.
func TestHooksKeepTheirOwnSessionState(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()
	stateDir := filepath.Join(s.dir, "state")
	if err := os.MkdirAll(stateDir, 0o755); err != nil {
		t.Fatal(err)
	}
	// A record of another interface must survive our teardown.
	if err := os.WriteFile(filepath.Join(stateDir, "ppp2.dns"), []byte("nameserver 203.0.113.99\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	s.run(hookEnv{
		script: "90-warnflux-gsm",
		args:   pppArgs("ppp0", "warnflux-gsm"),
		env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "198.51.100.53", "DNS2": "198.51.100.54"},
	})
	own := read(t, filepath.Join(stateDir, "ppp0.dns"))
	if !strings.Contains(own, "nameserver 198.51.100.53") || !strings.Contains(own, "nameserver 198.51.100.54") {
		t.Errorf("ip-up did not record the session's resolvers:\n%s", own)
	}

	s.run(hookEnv{script: "90-warnflux-gsm-down", args: pppArgs("ppp0", "warnflux-gsm"),
		env: map[string]string{"WARNFLUX_RESOLVCONF": conf}})
	if _, err := os.Stat(filepath.Join(stateDir, "ppp0.dns")); !os.IsNotExist(err) {
		t.Errorf("ip-down left its own state behind (err=%v)", err)
	}
	if _, err := os.Stat(filepath.Join(stateDir, "ppp2.dns")); err != nil {
		t.Errorf("ip-down removed another interface's state: %v", err)
	}
}

// watchdogStation is a scratch host for the failover watchdog: a routing table
// in a file, an `ip` that edits it and can be told to fail, a `ping` that answers
// for the wired link, and a state directory of our own.
type watchdogStation struct {
	*station
	routes string
}

func newWatchdogStation(t *testing.T) *watchdogStation {
	t.Helper()
	s := newStation(t)
	w := &watchdogStation{station: s, routes: filepath.Join(s.dir, "routes.txt")}
	if err := os.MkdirAll(filepath.Join(s.dir, "state"), 0o755); err != nil {
		t.Fatal(err)
	}
	// A healthy host: Ethernet at metric 100, the backup waiting at 700.
	w.setRoutes("default via 10.0.0.1 dev eth0 proto static metric 100", "default dev ppp0 scope link metric 700")
	return w
}

func (w *watchdogStation) setRoutes(lines ...string) {
	if err := os.WriteFile(w.routes, []byte(strings.Join(lines, "\n")+"\n"), 0o644); err != nil {
		w.t.Fatal(err)
	}
}

func (w *watchdogStation) routeLines() string {
	raw, err := os.ReadFile(w.routes)
	if err != nil {
		w.t.Fatal(err)
	}
	return string(raw)
}

func (w *watchdogStation) mode() string {
	raw, err := os.ReadFile(filepath.Join(w.dir, "state", "mode"))
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(raw))
}

func (w *watchdogStation) setMode(mode string) {
	if err := os.WriteFile(filepath.Join(w.dir, "state", "mode"), []byte(mode+"\n"), 0o644); err != nil {
		w.t.Fatal(err)
	}
}

// installIP writes the fake `ip`: it keeps the routing table in a file and fails
// the requested operation when the matching flag file exists.
func (w *watchdogStation) installIP() {
	w.t.Helper()
	script := `#!/bin/sh
echo "ip $*" >>` + filepath.Join(w.dir, "calls.log") + `
case "$2" in
show) cat ` + w.routes + `; exit 0 ;;
del)
	if [ -f ` + filepath.Join(w.dir, "fail-del") + ` ]; then exit 2; fi
	grep -v "dev $5 .*metric $7" ` + w.routes + ` > ` + w.routes + `.new; mv ` + w.routes + `.new ` + w.routes + `
	exit 0 ;;
replace)
	if [ -f ` + filepath.Join(w.dir, "fail-replace") + ` ]; then exit 2; fi
	echo "default dev $5 scope link metric $7" >> ` + w.routes + `
	exit 0 ;;
esac
exit 0
`
	if err := os.WriteFile(filepath.Join(w.dir, "bin", "ip"), []byte(script), 0o755); err != nil {
		w.t.Fatal(err)
	}
}

// run starts the watchdog with the wired link answering (answer=true) or not.
func (w *watchdogStation) run(answer bool) (string, error) {
	w.t.Helper()
	ping := "#!/bin/sh\nexit " + map[bool]string{true: "0", false: "1"}[answer] + "\n"
	if err := os.WriteFile(filepath.Join(w.dir, "bin", "ping"), []byte(ping), 0o755); err != nil {
		w.t.Fatal(err)
	}
	cmd := exec.Command("sh", mustAbs(w.t, "warnflux-net-watchdog.sh"))
	cmd.Dir = mustAbs(w.t, ".")
	cmd.Env = []string{
		"PATH=" + filepath.Join(w.dir, "bin") + ":/usr/bin:/bin",
		"WARNFLUX_NET_STATE_DIR=" + filepath.Join(w.dir, "state"),
		"WARNFLUX_GSM_DNS=" + filepath.Join(mustAbs(w.t, "."), "warnflux-gsm-dns"),
		"PROBE_HOSTS=192.0.2.1",
		"FAIL_THRESHOLD=1",
		"OK_THRESHOLD=1",
		"PING_COUNT=1",
		"PING_WAIT=1",
	}
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// TestWatchdogRetriesAFailedRecovery is WF-R2-03: `ip route del` failed, so the
// metric-50 route survived — and the watchdog still wrote "primary" and logged a
// recovery, never to try again. The routing table now decides: the mode stays
// cellular until the route is really gone.
func TestWatchdogRetriesAFailedRecovery(t *testing.T) {
	w := newWatchdogStation(t)
	w.installIP()
	w.setRoutes(
		"default dev ppp0 scope link metric 50",
		"default via 10.0.0.1 dev eth0 proto static metric 100",
		"default dev ppp0 scope link metric 700",
	)
	w.setMode("cellular")

	// The wired link answers again, but the route cannot be removed.
	if err := os.WriteFile(filepath.Join(w.dir, "fail-del"), nil, 0o644); err != nil {
		t.Fatal(err)
	}
	if out, err := w.run(true); err != nil {
		t.Fatalf("watchdog failed: %v\n%s", err, out)
	}
	if got := w.mode(); got != "cellular" {
		t.Fatalf("mode = %q, want cellular while the forced route is still there", got)
	}
	if !strings.Contains(w.routeLines(), "metric 50") {
		t.Fatalf("the fixture lost its forced route")
	}

	// The removal works on the retry: now the station may say primary.
	if err := os.Remove(filepath.Join(w.dir, "fail-del")); err != nil {
		t.Fatal(err)
	}
	if out, err := w.run(true); err != nil {
		t.Fatalf("watchdog failed: %v\n%s", err, out)
	}
	if got := w.mode(); got != "primary" {
		t.Errorf("mode = %q, want primary once the route is gone", got)
	}
	if strings.Contains(w.routeLines(), "metric 50") {
		t.Errorf("the forced route is still in the table:\n%s", w.routeLines())
	}
	if n := strings.Count(w.calls(), "route del default dev ppp0 metric 50"); n != 2 {
		t.Errorf("route del was attempted %d times, want 2 (the retry included)", n)
	}
}

// TestWatchdogDoesNotClaimAFailoverItCouldNotRaise is the other half: a failing
// `ip route replace` must not be announced as "the station is on cellular".
func TestWatchdogDoesNotClaimAFailoverItCouldNotRaise(t *testing.T) {
	w := newWatchdogStation(t)
	w.installIP()
	if err := os.WriteFile(filepath.Join(w.dir, "fail-replace"), nil, 0o644); err != nil {
		t.Fatal(err)
	}

	out, err := w.run(false) // the wire is dead
	if err == nil {
		t.Fatalf("watchdog reported success although the route could not be raised\n%s", out)
	}
	if got := w.mode(); got == "cellular" {
		t.Errorf("mode = cellular although the forced route was never installed")
	}

	// With the route in place the failover is claimed once.
	if err := os.Remove(filepath.Join(w.dir, "fail-replace")); err != nil {
		t.Fatal(err)
	}
	if out, err := w.run(false); err != nil {
		t.Fatalf("watchdog failed: %v\n%s", err, out)
	}
	if got := w.mode(); got != "cellular" {
		t.Errorf("mode = %q, want cellular", got)
	}
	if !strings.Contains(w.routeLines(), "metric 50") {
		t.Errorf("the forced route is missing:\n%s", w.routeLines())
	}
}
