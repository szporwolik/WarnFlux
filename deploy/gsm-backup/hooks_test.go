// Package gsmbackup holds no code: the cellular backup uplink is shell scripts
// installed on the station host. The tests here run those scripts against a
// throwaway resolv.conf and a fake "ip"/"resolvectl", because the two defects
// they pin — a replaced /etc/resolv.conf symlink (WF-REV-05) and hooks that
// fire for links WarnFlux does not own (WF-REV-06) — only show up at the
// boundary between the script and the host.
package gsmbackup

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// hookEnv is one hook invocation: the script, pppd's six arguments and the
// environment the script may read.
type hookEnv struct {
	script string
	args   []string
	env    map[string]string
}

// station is a scratch host: a resolv.conf, a PATH holding fake ip/resolvectl
// binaries that record what they were asked to do, and the DNS helper from the
// repository.
type station struct {
	t   *testing.T
	dir string
}

func newStation(t *testing.T) *station {
	t.Helper()
	dir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(dir, "bin"), 0o755); err != nil {
		t.Fatal(err)
	}
	s := &station{t: t, dir: dir}
	// The host running these tests may well have systemd-resolved of its own;
	// the default station must not find it, or the helper would talk to the real
	// daemon instead of the scratch resolv.conf.
	body := "#!/bin/sh\nexit 1\n"
	if err := os.WriteFile(filepath.Join(dir, "bin", "resolvectl"), []byte(body), 0o755); err != nil {
		t.Fatal(err)
	}
	return s
}

// recorder installs a fake command that appends its arguments to calls.log.
func (s *station) recorder(name string) {
	s.t.Helper()
	body := "#!/bin/sh\necho \"" + name + " $*\" >>" + filepath.Join(s.dir, "calls.log") + "\nexit 0\n"
	if err := os.WriteFile(filepath.Join(s.dir, "bin", name), []byte(body), 0o755); err != nil {
		s.t.Fatal(err)
	}
}

// silentResolved installs a resolvectl that answers "status" successfully, which
// is how the helper decides the daemon owns the resolver.
func (s *station) silentResolved() {
	s.t.Helper()
	body := "#!/bin/sh\necho \"resolvectl $*\" >>" + filepath.Join(s.dir, "calls.log") + "\nexit 0\n"
	if err := os.WriteFile(filepath.Join(s.dir, "bin", "resolvectl"), []byte(body), 0o755); err != nil {
		s.t.Fatal(err)
	}
}

func (s *station) calls() string {
	s.t.Helper()
	raw, err := os.ReadFile(filepath.Join(s.dir, "calls.log"))
	if err != nil {
		return ""
	}
	return string(raw)
}

// writeConf creates resolv.conf with the wired resolver, and returns its path.
func (s *station) writeConf() string {
	s.t.Helper()
	path := filepath.Join(s.dir, "resolv.conf")
	body := "# generated by NetworkManager\nnameserver 10.0.0.1\n"
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		s.t.Fatal(err)
	}
	return path
}

// read returns the current content of a file.
func read(t *testing.T, path string) string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	return string(raw)
}

// run executes one hook with the scratch station's PATH and environment.
func (s *station) run(h hookEnv) {
	s.t.Helper()
	script, err := filepath.Abs(h.script)
	if err != nil {
		s.t.Fatal(err)
	}
	cmd := exec.Command("sh", append([]string{script}, h.args...)...)
	env := []string{
		"PATH=" + filepath.Join(s.dir, "bin") + ":/usr/bin:/bin",
		"WARNFLUX_GSM_DNS=" + filepath.Join(mustAbs(s.t, "."), "warnflux-gsm-dns"),
		"WARNFLUX_GSM_STATE_DIR=" + filepath.Join(s.dir, "state"),
	}
	for k, v := range h.env {
		env = append(env, k+"="+v)
	}
	cmd.Env = env
	out, err := cmd.CombinedOutput()
	if err != nil {
		s.t.Fatalf("%s %v failed: %v\n%s", h.script, h.args, err, out)
	}
}

func mustAbs(t *testing.T, p string) string {
	t.Helper()
	abs, err := filepath.Abs(p)
	if err != nil {
		t.Fatal(err)
	}
	return abs
}

// pppArgs is what pppd hands an ip-up.d/ip-down.d script.
func pppArgs(iface, ipparam string) []string {
	return []string{iface, "/dev/ttyUSB0", "115200", "10.46.23.112", "10.64.64.64", ipparam}
}

// TestHooksIgnoreForeignPPPProfiles is WF-REV-06: ip-up.d/ip-down.d are global,
// so a VPN or a second modem must not have its link routed by us, nor lose a
// resolver block that belongs to the backup link.
func TestHooksIgnoreForeignPPPProfiles(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()
	before := read(t, conf)

	for _, script := range []string{"90-warnflux-gsm", "90-warnflux-gsm-down"} {
		s.run(hookEnv{
			script: script,
			args:   pppArgs("ppp1", ""),
			env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "10.0.0.53"},
		})
		s.run(hookEnv{
			script: script,
			args:   pppArgs("ppp1", "some-vpn"),
			env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "10.0.0.53"},
		})
	}
	if got := read(t, conf); got != before {
		t.Errorf("a foreign profile rewrote resolv.conf:\n%s", got)
	}
	if calls := s.calls(); strings.Contains(calls, "default") {
		t.Errorf("a foreign profile changed the routing table: %s", calls)
	}
}

// TestOwnProfileWorksAsPPP1 is the other half of WF-REV-06: the profile check
// must follow ipparam, not the interface name — a replug can hand the backup
// link ppp1.
func TestOwnProfileWorksAsPPP1(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()

	s.run(hookEnv{
		script: "90-warnflux-gsm",
		args:   pppArgs("ppp1", "warnflux-gsm"),
		env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "10.0.0.53", "DNS2": "10.0.0.54"},
	})
	calls := s.calls()
	if !strings.Contains(calls, "ip route replace default dev ppp1 metric 700") {
		t.Errorf("the backup link did not get its route: %s", calls)
	}
	body := read(t, conf)
	if !strings.Contains(body, "nameserver 10.0.0.53") || !strings.Contains(body, "nameserver 10.0.0.54") {
		t.Errorf("the fallback resolvers are missing:\n%s", body)
	}
	if !strings.Contains(body, "nameserver 10.0.0.1") {
		t.Errorf("the wired resolver was dropped:\n%s", body)
	}
}

// TestDownKeepsTheResolvConfSymlink is WF-REV-05: on a host where resolv.conf is
// a symlink into a manager-owned file, "mv" replaced the link with a plain file
// and every later update landed somewhere nobody read.
func TestDownKeepsTheResolvConfSymlink(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	target := filepath.Join(s.dir, "run-resolv.conf")
	if err := os.WriteFile(target, []byte("# NetworkManager\nnameserver 10.0.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(s.dir, "resolv.conf")
	if err := os.Symlink(target, link); err != nil {
		t.Fatal(err)
	}

	s.run(hookEnv{
		script: "90-warnflux-gsm",
		args:   pppArgs("ppp0", "warnflux-gsm"),
		env:    map[string]string{"WARNFLUX_RESOLVCONF": link, "DNS1": "10.0.0.53"},
	})
	if !strings.Contains(read(t, target), "nameserver 10.0.0.53") {
		t.Fatalf("the fallback resolver did not reach the file behind the link:\n%s", read(t, target))
	}

	s.run(hookEnv{
		script: "90-warnflux-gsm-down",
		args:   pppArgs("ppp0", "warnflux-gsm"),
		env:    map[string]string{"WARNFLUX_RESOLVCONF": link},
	})

	info, err := os.Lstat(link)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("resolv.conf is no longer a symlink after ip-down")
	}
	body := read(t, target)
	if strings.Contains(body, "warnflux-gsm-backup") || strings.Contains(body, "nameserver 10.0.0.53") {
		t.Errorf("the backup block survived ip-down:\n%s", body)
	}
	if !strings.Contains(body, "nameserver 10.0.0.1") {
		t.Errorf("the wired resolver was lost:\n%s", body)
	}

	// The manager now updates the file the link points at; the station must see
	// it. This is what a replaced symlink silently broke.
	if err := os.WriteFile(target, []byte("nameserver 10.0.0.1\nnameserver 10.0.0.2\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(read(t, link), "nameserver 10.0.0.2") {
		t.Errorf("a later resolver update is invisible through resolv.conf")
	}
}

// TestResolvedConfKeepsTheWiredResolver is the station's real shape: pppd's
// distro hook (0000usepeerdns) has already rewritten the file with the operator
// resolvers alone, and those only answer from the mobile network. The wired
// resolver — recorded in pppd's own pre-connect copy — must come back first, or
// every lookup on the healthy wired link hangs.
func TestResolvedConfKeepsTheWiredResolver(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()
	// What 0000usepeerdns leaves behind, plus its backup of the wired state.
	if err := os.WriteFile(conf, []byte("# PPP: written by 0000usepeerdns\nnameserver 194.204.159.1\nnameserver 194.204.152.34\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(conf+".pppd-backup.ppp0", []byte("# Generated by NetworkManager\nnameserver 10.0.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	s.run(hookEnv{
		script: "90-warnflux-gsm",
		args:   pppArgs("ppp0", "warnflux-gsm"),
		env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "194.204.159.1", "DNS2": "194.204.152.34"},
	})

	body := read(t, conf)
	first := ""
	for _, line := range strings.Split(body, "\n") {
		if strings.HasPrefix(line, "nameserver ") {
			first = strings.TrimSpace(strings.TrimPrefix(line, "nameserver "))
			break
		}
	}
	if first != "10.0.0.1" {
		t.Errorf("first resolver is %q, want the wired 10.0.0.1:\n%s", first, body)
	}
	if !strings.Contains(body, "warnflux-gsm-backup") {
		t.Errorf("the fallback block is missing:\n%s", body)
	}
	if n := strings.Count(body, "nameserver 194.204.159.1"); n != 1 {
		t.Errorf("the operator resolver appears %d times, want 1:\n%s", n, body)
	}
}

// TestPreferFollowsTheActiveLink is the failover half of the resolver work: the
// operator's servers answer only on the mobile network, so once the cellular
// route wins they must be queried first — a dead first entry costs a timeout on
// every lookup — and the wired one must lead again after the recovery.
func TestPreferFollowsTheActiveLink(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()
	if err := os.WriteFile(conf+".pppd-backup.ppp0", []byte("nameserver 10.0.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	s.run(hookEnv{
		script: "90-warnflux-gsm",
		args:   pppArgs("ppp0", "warnflux-gsm"),
		env:    map[string]string{"WARNFLUX_RESOLVCONF": conf, "DNS1": "194.204.159.1", "DNS2": "194.204.152.34"},
	})

	firstResolver := func() string {
		for _, line := range strings.Split(read(t, conf), "\n") {
			if strings.HasPrefix(line, "nameserver ") {
				return strings.TrimSpace(strings.TrimPrefix(line, "nameserver "))
			}
		}
		return ""
	}

	s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"prefer", "ppp0", "cellular"},
		env: map[string]string{"WARNFLUX_RESOLVCONF": conf}})
	if got := firstResolver(); got != "194.204.159.1" {
		t.Errorf("during failover the first resolver is %q, want the operator one", got)
	}
	body := read(t, conf)
	if !strings.Contains(body, "nameserver 10.0.0.1") {
		t.Errorf("the wired resolver was dropped:\n%s", body)
	}

	s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"prefer", "ppp0", "wired"},
		env: map[string]string{"WARNFLUX_RESOLVCONF": conf}})
	if got := firstResolver(); got != "10.0.0.1" {
		t.Errorf("after recovery the first resolver is %q, want the wired one", got)
	}
	if n := strings.Count(read(t, conf), "nameserver 194.204.159.1"); n != 1 {
		t.Errorf("the operator resolver appears %d times, want 1", n)
	}
}

// TestEnsureHealsARegeneratedResolvConf is the gap the watchdog closes:
// NetworkManager rewrites resolv.conf whenever the wired network changes and
// silently drops the operator block, leaving the station with no resolver the
// backup link can reach. The watchdog calls "ensure" every 30 s, which rebuilds
// the block from the list pppd recorded — and does nothing while it is intact.
func TestEnsureHealsARegeneratedResolvConf(t *testing.T) {
	s := newStation(t)
	s.recorder("ip")
	conf := s.writeConf()
	if err := os.WriteFile(conf+".pppd-backup.ppp0", []byte("nameserver 10.0.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	env := map[string]string{"WARNFLUX_RESOLVCONF": conf}
	if err := os.MkdirAll(filepath.Join(s.dir, "state"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(s.dir, "state", "ppp0.dns"),
		[]byte("# warnflux-gsm session ppp0\nnameserver 194.204.159.1\nnameserver 194.204.152.34\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	// A regenerated file: no block at all.
	if strings.Contains(read(t, conf), "warnflux-gsm-backup") {
		t.Fatalf("the fixture already carries the block")
	}
	s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"ensure", "ppp0", "wired"}, env: env})
	body := read(t, conf)
	if !strings.Contains(body, "nameserver 194.204.159.1") || !strings.Contains(body, "warnflux-gsm-backup") {
		t.Fatalf("the fallback block was not rebuilt:\n%s", body)
	}
	if !strings.Contains(body, "nameserver 10.0.0.1") {
		t.Errorf("the wired resolver was lost:\n%s", body)
	}

	// A second pass must be a no-op, or every 30 s would rewrite the file.
	s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"ensure", "ppp0", "wired"}, env: env})
	if again := read(t, conf); again != body {
		t.Errorf("a repeated ensure changed the file:\n%s\nwant:\n%s", again, body)
	}

	// In failover mode the reachable servers lead.
	s.run(hookEnv{script: "warnflux-gsm-dns", args: []string{"ensure", "ppp0", "cellular"}, env: env})
	for _, line := range strings.Split(read(t, conf), "\n") {
		if strings.HasPrefix(line, "nameserver ") {
			if got := strings.TrimSpace(strings.TrimPrefix(line, "nameserver ")); got != "194.204.159.1" {
				t.Errorf("during failover the first resolver is %q, want the operator one", got)
			}
			break
		}
	}
}

